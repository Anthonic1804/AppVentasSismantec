package com.example.acae30.data.local.views

import androidx.room.DatabaseView

@DatabaseView(
    viewName = "detalle_producto",
    value = """
        SELECT
            detalle_pedidos.id,
            detalle_pedidos.id_pedido,
            detalle_pedidos.id_producto,
            inventario.codigo,
            detalle_pedidos.descripcion,
            inventario.costo,
            inventario.costo_iva,
            inventario.precio,
            inventario.precio_iva,
            inventario.precio_u,
            inventario.precio_u_iva,
            detalle_pedidos.cantidad,
            detalle_pedidos.precio AS Precio_venta_siva,
            detalle_pedidos.precio_iva AS precio_venta,
            detalle_pedidos.total,
            detalle_pedidos.total_iva,
            detalle_pedidos.unidad,
            detalle_pedidos.bonificado,
            detalle_pedidos.descuento,
            detalle_pedidos.precio_editado,
            detalle_pedidos.idunidad,
            detalle_pedidos.Codigo_de_barra,
            detalle_pedidos.EquivaleUni,
            detalle_pedidos.EquivaleFra,
            detalle_pedidos.UniEquivale,
            detalle_pedidos.Tipo,
            detalle_pedidos.IdMarca,
            detalle_pedidos.IdSku,
            detalle_pedidos.IdLinea,
            detalle_pedidos.IdSubLinea,
            detalle_pedidos.IdRubro,
            detalle_pedidos.IdProductor,
            detalle_pedidos.IdProveedor,
            detalle_pedidos.Metodo_gestion,
            detalle_pedidos.Tipo_fiscal,
            detalle_pedidos.IdLote,
            detalle_pedidos.Lote,
            detalle_pedidos.FechaVencimiento,
            detalle_pedidos.IdBodega,
            detalle_pedidos.CodBodega,
            detalle_pedidos.Bodega,
            detalle_pedidos.Orden_despacho
        FROM detalle_pedidos
        LEFT JOIN inventario
            ON inventario.Id = detalle_pedidos.Id_producto
    """
)
data class DetalleProductoView(
    val id: Int,
    val id_pedido: Int,
    val id_producto: Int,
    val codigo: String?,
    val descripcion: String?,
    val costo: Double?,
    val costo_iva: Double?,
    val precio: Double?,
    val precio_iva: Double?,
    val precio_u: Double?,
    val precio_u_iva: Double?,
    val cantidad: Double?,
    val Precio_venta_siva: Double?,
    val precio_venta: Double?,
    val total: Double?,
    val total_iva: Double?,
    val unidad: String?,
    val bonificado: Int?,
    val descuento: Double?,
    val precio_editado: Int?,
    val idunidad: Int?,
    val Codigo_de_barra: String?,
    val EquivaleUni: Double?,
    val EquivaleFra: Double?,
    val UniEquivale: Double?,
    val Tipo: String?,
    val IdMarca: Int?,
    val IdSku: Int?,
    val IdLinea: Int?,
    val IdSubLinea: Int?,
    val IdRubro: Int?,
    val IdProductor: Int?,
    val IdProveedor: Int?,
    val Metodo_gestion: String?,
    val Tipo_fiscal: String?,
    val IdLote: Int?,
    val Lote: String?,
    val FechaVencimiento: String?,
    val IdBodega: Int?,
    val CodBodega: String?,
    val Bodega: String?,
    val Orden_despacho: Int?
)